-- Removes a sitio/purok: deleted when no farmer has it, otherwise hidden
-- (deactivated: no longer offered, kept on the farmers who have it).
-- Returns 'deleted' or 'hidden'.
create or replace function public.remove_sitio(p_id bigint)
returns text
language plpgsql
security definer
set search_path = public
as $function$
declare
  v_sitio record;
begin
  select id, name, barangay_id into v_sitio from public.sitios where id = p_id;
  if not found then
    raise exception 'That sitio/purok is no longer on the list. Refresh to see the current list.';
  end if;
  if not (public.current_role() = 'mao_admin'
          or (public.current_role() = 'fa_president' and v_sitio.barangay_id = public.my_barangay_id())) then
    raise exception 'You can only manage your own barangay''s sitios/puroks.';
  end if;
  if exists (select 1 from public.addresses a
             where a.sitio_id = p_id
                or (a.sitio_id is null and coalesce(a.barangay_id, public.barangay_id_for(a.barangay)) = v_sitio.barangay_id
                    and public.list_name_key(a.street) = public.list_name_key(v_sitio.name)))
     or exists (select 1 from public.farm_parcels p where p.sitio_id = p_id) then
    update public.sitios set is_active = false where id = p_id;
    return 'hidden';
  end if;
  delete from public.sitios where id = p_id;
  return 'deleted';
end;
$function$;
revoke execute on function public.remove_sitio(bigint) from anon, public;
grant execute on function public.remove_sitio(bigint) to authenticated;

-- ---------------------------------------------------------------------------
-- List usage (Settings → Lists): adds the types of farmer.
-- ---------------------------------------------------------------------------
create or replace function public.list_usage()
returns table(list text, id bigint, uses bigint)
language sql
stable security definer
set search_path = public
as $function$
  select 'sitios', s.id, (
    select count(distinct u.farmer_id) from (
      select a.farmer_id from public.addresses a
        where a.sitio_id = s.id or (a.sitio_id is null and public.list_name_key(a.street) = public.list_name_key(s.name))
      union all
      select p.farmer_id from public.farm_parcels p
        where p.sitio_id = s.id or (p.sitio_id is null and public.list_name_key(p.farm_location) = public.list_name_key(s.name))
    ) u)
  from public.sitios s
  where public.current_role() = 'mao_admin'
  union all
  select 'associations', x.id, (
    select count(*) from public.farmers f
    where f.association_id = x.id or (f.association_id is null and public.list_name_key(f.org_affiliation) = public.list_name_key(x.name)))
  from public.associations x
  where public.current_role() = 'mao_admin'
  union all
  select 'crop_types', t.id, (
    select count(distinct p.farmer_id) from public.crops c join public.farm_parcels p on p.parcel_id = c.parcel_id
    where c.crop_type_id = t.id or (c.crop_type_id is null and public.list_name_key(c.crop_type) = public.list_name_key(t.name)))
  from public.crop_types t
  where public.current_role() = 'mao_admin'
  union all
  select 'barangays', b.id, (
    select count(distinct a.farmer_id) from public.addresses a join public.farmers f on f.farmer_id = a.farmer_id and f.deleted_at is null
    where a.barangay_id = b.id or (a.barangay_id is null and public.barangay_id_for(a.barangay) = b.id))
  from public.barangays b
  where public.current_role() = 'mao_admin'
  union all
  select 'farmer_types', t.id, (
    select count(*) from public.farmer_farmer_types x join public.farmers f on f.farmer_id = x.farmer_id and f.deleted_at is null
    where x.farmer_type_id = t.id)
  from public.farmer_types t
  where public.current_role() = 'mao_admin';
$function$;

-- ---------------------------------------------------------------------------
-- Distributions: the Active farmers of a type in a barangay, with any
-- repeat of this commodity under this program this year.
-- ---------------------------------------------------------------------------
create or replace function public.farmers_of_type(
  p_farmer_type_id bigint,
  p_barangay_id bigint,
  p_commodity_id bigint default null,
  p_program_name text default null,
  p_year integer default null,
  p_exclude_event_id bigint default null
)
returns table(farmer_id bigint, rsbsa_no text, first_name text, surname text, barangay text, sitio_purok text,
              farm_size_hectares numeric, avatar_url text, duplicate_program text, duplicate_date date, duplicate_quantity numeric)
language sql
stable security definer
set search_path = public
as $function$
  select f.farmer_id, f.rsbsa_no, f.first_name, f.surname, coalesce(addr.barangay, ''), addr.street,
         public.farmer_farm_size(f.farmer_id), p.avatar_url,
         dup.program_name, dup.event_date, dup.quantity_received
  from public.farmers f
  join public.farmer_farmer_types t on t.farmer_id = f.farmer_id and t.farmer_type_id = p_farmer_type_id
  left join lateral (
    select a.barangay, a.street from public.addresses a where a.farmer_id = f.farmer_id order by a.address_id limit 1
  ) addr on true
  left join public.profiles p on p.id = f.profile_id
  left join lateral (
    select * from public.find_duplicate_distribution(f.farmer_id, p_commodity_id, p_program_name, coalesce(p_year, extract(year from now())::int), p_exclude_event_id)
  ) dup on p_commodity_id is not null and nullif(btrim(coalesce(p_program_name, '')), '') is not null
  where public.current_role() = 'mao_admin'
    and f.deleted_at is null
    and f.status = 'active'
    and (p_barangay_id is null or public.farmer_barangay_id(f.farmer_id) = p_barangay_id)
  order by f.surname, f.first_name
$function$;
revoke execute on function public.farmers_of_type(bigint, bigint, bigint, text, integer, bigint) from anon, public;
grant execute on function public.farmers_of_type(bigint, bigint, bigint, text, integer, bigint) to authenticated;

