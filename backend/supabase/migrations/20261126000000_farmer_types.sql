-- Types of farmer, 11-digit contact numbers, new farmers Active, sitios
-- managed by the Farmers' Association President, harvest reports Rejected
-- instead of Returned, and tagging beneficiaries by type of farmer
-- (Nov 26, 2026).
--
-- * farmer_types (the MAO Admin edits it in Settings) and
--   farmer_farmer_types: a farmer has one or more types. They replace the
--   farmer's Commodity / Crop Type and Seed Program, whose columns stay in
--   place, unused. Existing crops become types: Rice → Rice farmer, Corn →
--   Corn farmer, Vegetables → Vegetable farmer.
-- * commodities.farmer_type_id: who a commodity is for (Corn Seeds → Corn
--   farmer), suggested when tagging a distribution's beneficiaries.
-- * Contact numbers: 11 digits starting with 09. Checked for new and changed
--   rows (NOT VALID: existing numbers are listed for the MAO, not changed).
-- * save_farmer: types (at least one) instead of crop and seed program; a
--   new farmer is always Active; the contact number is checked.
-- * Sitios/puroks: the Farmers' Association President renames and removes
--   their own barangay's; remove_sitio deletes an unused one and hides one
--   that farmers have.
-- * Harvest reports: the "returned" status is renamed "rejected" (existing
--   reports follow), with the notification wording.
-- * farmers_of_type: the Active farmers of a type in a barangay, for "Tag by
--   type of farmer" (MAO Admin).

-- ---------------------------------------------------------------------------
-- Types of farmer
-- ---------------------------------------------------------------------------
create table public.farmer_types (
  id bigint generated by default as identity primary key,
  name text not null,
  examples text,
  sort_order integer not null default 0,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  created_by uuid default auth.uid() references auth.users (id) on delete set null,
  constraint farmer_types_examples_length check (examples is null or char_length(examples) <= 200)
);
create unique index farmer_types_name_key on public.farmer_types (public.list_name_key(name));

create trigger clean_list_name before insert or update on public.farmer_types
  for each row execute function public.clean_list_name();
create trigger audit_farmer_types after insert or update or delete on public.farmer_types
  for each row execute function public.log_audit_event();

alter table public.farmer_types enable row level security;
create policy "farmer types: signed-in users read" on public.farmer_types
  for select to authenticated using (true);
create policy "farmer types: MAO adds" on public.farmer_types
  for insert to authenticated with check (public.current_role() = 'mao_admin');
create policy "farmer types: MAO edits" on public.farmer_types
  for update to authenticated using (public.current_role() = 'mao_admin') with check (public.current_role() = 'mao_admin');
create policy "farmer types: MAO deletes" on public.farmer_types
  for delete to authenticated using (public.current_role() = 'mao_admin');
revoke all on public.farmer_types from anon;
grant select, insert, update, delete on public.farmer_types to authenticated;

