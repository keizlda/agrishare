-- Existing crops become types (the crop list entry's name, or the crop text).
insert into public.farmer_farmer_types (farmer_id, farmer_type_id)
select distinct p.farmer_id, t.id
from public.crops c
join public.farm_parcels p on p.parcel_id = c.parcel_id
left join public.crop_types ct on ct.id = c.crop_type_id
join public.farmer_types t on t.name = case lower(btrim(coalesce(ct.name, c.crop_type)))
  when 'rice' then 'Rice farmer'
  when 'palay' then 'Rice farmer'
  when 'corn' then 'Corn farmer'
  when 'vegetable' then 'Vegetable farmer'
  when 'vegetables' then 'Vegetable farmer'
end
on conflict do nothing;

-- Who a commodity is for.
alter table public.commodities add column farmer_type_id bigint references public.farmer_types (id) on delete set null;
update public.commodities c set farmer_type_id = t.id
from public.farmer_types t
where c.farmer_type_id is null
  and t.name = case lower(btrim(coalesce(c.category, '')))
    when 'rice' then 'Rice farmer'
    when 'corn' then 'Corn farmer'
    when 'vegetables' then 'Vegetable farmer'
  end;

